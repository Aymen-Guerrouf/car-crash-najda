export const STRINGS: Record<Language, Strings> = { fr, ar };

export const LANGUAGE_LABELS: Record<Language, string> = { ar: 'العربية', fr: 'Français' };

export function useT(): Strings {
  const language = useProfileStore((s) => s.language);
  return STRINGS[language];
}

/** Layout direction helper: Arabic mirrors rows and aligns text to the right. */
export function useDir() {
  const language = useProfileStore((s) => s.language);
  const rtl = language === 'ar';
  return {
    language,
    rtl,
    row: (rtl ? 'row-reverse' : 'row') as 'row' | 'row-reverse',
    align: (rtl ? 'right' : 'left') as 'right' | 'left',
    chevron: (rtl ? 'chevron-back' : 'chevron-forward') as 'chevron-back' | 'chevron-forward',
  };
}
